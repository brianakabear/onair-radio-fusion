// Helper function to extract relevant topics from content
const extractTopics = (content: string): string[] => {
  const commonTopics = [
    "reggae music", "dancehall culture", "Caribbean artists", "music industry",
    "festival culture", "international collaboration", "cultural heritage",
    "artist development", "music production", "live performance", "streaming success",
    "Grammy recognition", "cross-cultural exchange", "musical legacy"
  ];
  
  return commonTopics.filter(topic => 
    content.toLowerCase().includes(topic.toLowerCase())
  ).slice(0, 4);
};